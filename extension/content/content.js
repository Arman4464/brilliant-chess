/**
 * Chess.com Review Extractor - Content Script
 */

(function () {
  const wait = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

  function showToast(message, type = 'success') {
    const existing = document.querySelector('.chess-review-toast');
    if (existing) existing.remove();

    const toast = document.createElement('div');
    toast.className = `chess-review-toast ${type}`;
    toast.innerText = message;
    document.body.appendChild(toast);

    setTimeout(() => {
      toast.style.opacity = '0';
      toast.style.transition = 'opacity 0.5s ease';
      setTimeout(() => toast.remove(), 500);
    }, 4000);
  }

  function downloadJson(data, filename) {
    const blob = new Blob([JSON.stringify(data, null, 2)], { type: 'application/json' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = filename;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  }

  function isReviewPage() {
    return window.location.pathname.includes('/review');
  }

  function checkDailyLimitReached() {
    const modal = document.querySelector('[role="dialog"], [class*="modal"]');
    return modal && modal.innerText.includes('DAILY LIMIT REACHED');
  }

  async function performExtraction() {
    const exportBtn = document.querySelector('.chess-review-exporter-btn');
    if (exportBtn) {
      exportBtn.classList.add('extracting');
      exportBtn.innerText = '⏳ Extracting...';
    }

    try {
      // 1. Check if daily limit reached
      if (checkDailyLimitReached()) {
        showToast('⚠️ Daily limit reached on Chess.com. Review not generated by Chess.com.', 'warning');
        if (exportBtn) {
          exportBtn.classList.remove('extracting');
          exportBtn.innerText = '📥 Export Review';
        }
        return { error: 'DAILY_LIMIT_REACHED' };
      }

      // 2. Access board & game data
      const cb = document.querySelector('wc-chess-board');
      const game = cb?.game;
      const headers = game?.getHeaders?.() || {};
      const rawLines = game?.getRawLines?.()?.[0] || [];

      // 3. Switch back to overview if needed to read stats
      let backBtn = document.querySelector('button[aria-label="Back"]');
      if (backBtn) {
        backBtn.click();
        await wait(200);
      }

      const whiteAcc = document.querySelector('.review-rating-white span')?.innerText?.trim();
      const blackAcc = document.querySelector('.review-rating-black span')?.innerText?.trim();

      let whitePerfRating = null;
      let blackPerfRating = null;
      const ratingRows = Array.from(document.querySelectorAll('.game-overview-row'));
      for (const row of ratingRows) {
        if (row.innerText.includes('Game Rating')) {
          whitePerfRating = row.querySelector('.review-rating-white')?.innerText?.trim();
          blackPerfRating = row.querySelector('.review-rating-black')?.innerText?.trim();
        }
      }

      const tallies = {};
      const tallyRows = Array.from(document.querySelectorAll('.tally-row-row'));
      for (const r of tallyRows) {
        const title = r.querySelector('.tally-row-rowTitle')?.innerText?.trim()?.toLowerCase();
        const values = Array.from(r.querySelectorAll('.tally-row-value')).map((v) =>
          parseInt(v.innerText?.trim(), 10)
        );
        if (title && values.length >= 2) {
          tallies[title] = { white: values[0], black: values[1] };
        }
      }

      // 4. Start move-by-move view
      let startBtn =
        document.querySelector('.tab-review-start-review-button') ||
        Array.from(document.querySelectorAll('button')).find((b) =>
          b.innerText.includes('Start Review')
        );
      if (startBtn) {
        startBtn.click();
        for (let t = 0; t < 25; t++) {
          await wait(100);
          if (document.querySelector('.node[data-node]')) break;
        }
      }

      // 5. Step through moves
      const moveCount = rawLines.length;
      const moves = [];

      for (let i = 0; i < moveCount; i++) {
        const nodeEl = document.querySelector(`.node[data-node="0-${i}"]`);
        if (nodeEl) {
          nodeEl.click();
          await wait(35);

          const container = document.querySelector('.move-by-move-container');
          const lines = container ? container.innerText.split('\n') : [];

          const raw = rawLines[i] || {};
          const rawClass = lines[1] || '';
          const cleanClassification = rawClass
            .replace(/^is (the |an? )?/i, '')
            .replace(/ move$/i, '')
            .trim();

          moves.push({
            ply: i + 1,
            moveNumber: raw.wholeMoveNumber || Math.floor(i / 2) + 1,
            color: raw.color === 1 ? 'white' : 'black',
            san: raw.san || lines[0]?.trim(),
            classification: cleanClassification || 'regular',
            eval: lines[2] || null,
            clock: raw.commands?.clk || null,
            timeSpent: raw.time ? (raw.time / 1000).toFixed(1) + 's' : null,
            fen: raw.fen || null
          });
        }
      }

      const gameId =
        window.chesscom?.analysis?.gameId ||
        window.location.pathname.split('/').filter(Boolean)[3] ||
        'game';

      const reviewData = {
        game: {
          id: gameId,
          url: window.location.origin + window.location.pathname,
          date: headers.Date,
          timeControl: headers.TimeControl
            ? `${parseInt(headers.TimeControl, 10) / 60} min`
            : '10 min',
          eco: headers.ECO,
          opening: headers.ECOUrl ? headers.ECOUrl.split('/').pop().replace(/-/g, ' ') : 'Unknown',
          result: headers.Result,
          termination: headers.Termination
        },
        players: {
          white: {
            username: headers.White,
            rating: headers.WhiteElo ? parseInt(headers.WhiteElo, 10) : null,
            accuracy: whiteAcc ? parseFloat(whiteAcc) : null,
            performanceRating: whitePerfRating ? parseInt(whitePerfRating, 10) : null
          },
          black: {
            username: headers.Black,
            rating: headers.BlackElo ? parseInt(headers.BlackElo, 10) : null,
            accuracy: blackAcc ? parseFloat(blackAcc) : null,
            performanceRating: blackPerfRating ? parseInt(blackPerfRating, 10) : null
          }
        },
        tallies: tallies,
        totalMoves: moves.length,
        moves: moves
      };

      downloadJson(reviewData, `chesscom_review_${gameId}.json`);
      showToast(`✅ Downloaded review for Game #${gameId}!`);

      try {
        await navigator.clipboard.writeText(JSON.stringify(reviewData, null, 2));
      } catch (_) {}

      return { success: true, data: reviewData };
    } catch (err) {
      console.error('Extraction error:', err);
      showToast(`❌ Error: ${err.message}`, 'error');
      return { error: err.message };
    } finally {
      if (exportBtn) {
        exportBtn.classList.remove('extracting');
        exportBtn.innerText = '📥 Export Review';
      }
    }
  }

  // Inject floating button if on /review page
  function injectFloatingButton() {
    if (!isReviewPage() || document.querySelector('.chess-review-exporter-btn')) return;

    const btn = document.createElement('button');
    btn.className = 'chess-review-exporter-btn';
    btn.innerText = '📥 Export Review';
    btn.title = 'Extract & download complete game review JSON';
    btn.addEventListener('click', performExtraction);
    document.body.appendChild(btn);
  }

  // Observe page changes
  setInterval(() => {
    if (isReviewPage()) {
      injectFloatingButton();
    } else {
      const btn = document.querySelector('.chess-review-exporter-btn');
      if (btn) btn.remove();
    }
  }, 1000);

  // Message listener for popup
  chrome.runtime.onMessage.addListener((request, sender, sendResponse) => {
    if (request.action === 'GET_PAGE_STATUS') {
      const isReview = isReviewPage();
      const isLimit = checkDailyLimitReached();
      const gameId =
        window.chesscom?.analysis?.gameId ||
        window.location.pathname.split('/').filter(Boolean)[3] ||
        '';

      sendResponse({
        isReviewPage: isReview,
        dailyLimitReached: isLimit,
        gameId: gameId,
        url: window.location.href
      });
      return false;
    }

    if (request.action === 'START_EXTRACTION') {
      performExtraction().then((res) => {
        sendResponse(res);
      });
      return true; // async sendResponse
    }
  });
})();
